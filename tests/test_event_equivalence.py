"""Equivalence test for the reader: the built events must not change.

The fixture stores, for ten entries of the test ntuple, the particle count of
every collection and a digest of every attribute of every particle
(``tests/fixtures/event_snapshot.json``, generated by
``tests/gen_event_snapshot.py``). Any reader optimisation has to keep it green:
it is the only proof that a speed change is not a physics change.
"""

import json
import os
import sys

import pytest

HERE = os.path.dirname(os.path.abspath(__file__))
if HERE not in sys.path:
    sys.path.insert(0, HERE)

from event_digest import ROOT_DIR, snapshot  # noqa: E402

FIXTURE = os.path.join(HERE, "fixtures", "event_snapshot.json")


def _differences(expected, actual, path="", found=None):
    """Collect the paths at which two digest structures disagree."""
    if found is None:
        found = []
    if len(found) >= 20:
        return found
    if isinstance(expected, dict) and isinstance(actual, dict):
        for key in sorted(set(expected) | set(actual)):
            if key not in expected or key not in actual:
                found.append("%s/%s: only in one side" % (path, key))
                continue
            _differences(expected[key], actual[key], "%s/%s" % (path, key), found)
    elif isinstance(expected, list) and isinstance(actual, list):
        if len(expected) != len(actual):
            found.append("%s: length %d != %d" % (path, len(expected), len(actual)))
            return found
        for index, (left, right) in enumerate(zip(expected, actual)):
            _differences(left, right, "%s[%d]" % (path, index), found)
    elif expected != actual:
        found.append("%s: %r != %r" % (path, expected, actual))
    return found


def test_built_events_match_snapshot():
    if not os.path.exists(FIXTURE):
        pytest.skip("Missing fixture: run python tests/gen_event_snapshot.py")

    with open(FIXTURE) as handle:
        expected = json.load(handle)

    input_path = os.path.join(ROOT_DIR, expected["meta"]["input"])
    if not os.path.exists(input_path):
        pytest.skip("Test ROOT file not found: %s" % input_path)

    from dtpr.base import NTuple

    ntuple = NTuple(input_path)
    actual = snapshot(ntuple, expected["meta"]["entries"])

    differences = _differences(expected["events"], actual["events"])
    assert not differences, "Built events changed:\n  " + "\n  ".join(differences)
